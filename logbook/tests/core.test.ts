import { describe, expect, test } from 'claude-code/testing'
import { Book, dirsFor } from '../hooks/book'
import type { Entry, Io } from '../hooks/book'
import { parseReply, plan, transcript } from '../hooks/extract-core'
import { buildIndex, overlap, search, tokens } from '../hooks/index-core'
import type { Memory } from '../hooks/memory-core'
import { canMove, fromFile, makeMemory, move, newId, toFile } from '../hooks/memory-core'
import { recall, recallBlock, standing, standingSection } from '../hooks/pack-core'

const NOW = new Date('2026-11-24T12:00:00Z')
let seed = 0
const rand = () => ((seed = (seed * 9301 + 49297) % 233280) / 233280)
const mk = (text: string, kind: Memory['kind'] = 'decision', layer: Memory['layer'] = 'project', at = NOW) =>
  makeMemory({ text, kind, layer, source: 'manual', now: at, rand })

/** An in-memory file system standing in for $.fs. */
function memIo() {
  const files = new Map<string, string>()
  const io: Io = {
    read: async p => { const t = files.get(p); if (t === undefined) throw new Error('missing'); return t },
    write: async (p, t) => { files.set(p, t) },
    list: async dir => {
      const out: Entry[] = []
      for (const p of files.keys()) if (p.startsWith(`${dir}/`) && !p.slice(dir.length + 1).includes('/')) out.push({ name: p.slice(dir.length + 1), kind: 'file' })
      return out
    },
    exists: async dir => [...files.keys()].some(p => p.startsWith(`${dir}/`)),
  }
  return { io, files }
}

describe('memory model', () => {
  test('lifecycle allows only legal moves', () => {
    expect(canMove('active', 'revoked')).toBe(true)
    expect(canMove('revoked', 'active')).toBe(true)
    expect(canMove('superseded', 'revoked')).toBe(false)
    const m = mk('Use Postgres 17')
    expect(() => move(move(m, 'superseded', NOW), 'revoked', NOW)).toThrow()
  })

  test('file round trip keeps every field, including awkward text', () => {
    const m = { ...mk('Prices are "net" of VAT: never: gross'), evidence: 'said on: a call', supersedes: newId(NOW, rand) }
    const back = fromFile(toFile(m))
    expect(back).toEqual(m)
  })

  test('a broken or foreign file is not a memory', () => {
    expect(fromFile('# just notes')).toBeUndefined()
    expect(fromFile('---\nid: nope\nkind: decision\nlayer: project\nstatus: active\n---\ntext')).toBeUndefined()
    expect(fromFile(toFile(mk('x')).replace('kind: decision', 'kind: wish'))).toBeUndefined()
  })
})

describe('search', () => {
  test('stems and folds accents across English and Portuguese', () => {
    expect(tokens('Decisões de deployment')).toEqual(tokens('decisoes deploy'))
    expect(tokens('the migrations are reversible')).toEqual(['migr', 'reversible'])
  })

  test('ranks the memory about the asked topic first', () => {
    const ms = [mk('Deploys go through the staging cluster first'), mk('Use pnpm, never npm, in this repo', 'constraint'), mk('The billing service owns invoices')]
    const hits = search(buildIndex(ms), 'which package manager, npm or pnpm?')
    expect(hits[0]?.m.text).toContain('pnpm')
  })

  test('overlap sees a restatement as a duplicate', () => {
    expect(overlap('Use pnpm, never npm', 'never use npm; use pnpm')).toBe(1)
    expect(overlap('Use pnpm', 'Deploy on Fridays')).toBe(0)
  })
})

describe('packs', () => {
  test('standing pack holds constraints and preferences first, never restricted or inactive ones', () => {
    const secret = { ...mk('Staging password rotates monthly', 'constraint'), sensitivity: 'restricted' as const }
    const gone = move(mk('Old rule', 'constraint'), 'revoked', NOW)
    const ms = [mk('A note', 'note'), mk('Chose Drizzle over Prisma'), mk('Answer in Portuguese when asked in Portuguese', 'preference', 'personal'), mk('No paid inference APIs', 'constraint'), secret, gone]
    const pack = standing(ms)
    expect(pack.map(m => m.kind)).toEqual(['constraint', 'preference', 'decision'])
    const section = standingSection(ms)
    expect(section).toContain('## Yours (every folder)')
    expect(section).toContain('## This folder')
    expect(section).not.toContain('password')
  })

  test('standing pack respects its budget', () => {
    const ms = Array.from({ length: 200 }, (_, i) => mk(`Constraint number ${i} with some words to take room`, 'constraint'))
    const pack = standing(ms, 1000)
    expect(pack.length).toBeGreaterThan(5)
    expect(pack.map(m => `- [${m.kind}] ${m.text} ‹${m.id}›`).join('\n').length).toBeLessThanOrEqual(1000)
  })

  test('recall skips what the standing pack already carries and drops weak matches', () => {
    const a = mk('Invoices are generated by the billing worker nightly', 'fact')
    const b = mk('The billing worker retries three times', 'fact')
    const c = mk('Frontend uses the billing colour palette', 'note')
    const ix = buildIndex([a, b, c])
    const got = recall(ix, 'when does the billing worker generate invoices?', new Set([b.id]))
    expect(got[0]?.id).toBe(a.id)
    expect(got.some(m => m.id === b.id)).toBe(false)
    expect(recallBlock(got)).toContain('<logbook-recall>')
    expect(recallBlock([])).toBeUndefined()
  })
})

describe('capture', () => {
  test('transcript keeps the newest turns within budget', () => {
    const t = transcript([{ role: 'user', text: 'a'.repeat(100) }, { role: 'assistant', text: 'b'.repeat(100) }, { role: 'user', text: 'newest' }], 130)
    expect(t).toContain('PERSON: newest')
    expect(t).not.toContain('aaaa')
  })

  test('the model reply is validated, not trusted', () => {
    const reply = 'Sure! {"memories":[{"text":"Use pnpm","kind":"constraint","layer":"project"},{"text":"","kind":"fact","layer":"project"},{"text":"x","kind":"wish","layer":"project"},{"text":"Likes short answers","kind":"preference","layer":"PERSONAL","supersedes":"20261124-120000-aaaa"},"junk"]} done'
    const c = parseReply(reply)
    expect(c).toEqual([
      { text: 'Use pnpm', kind: 'constraint', layer: 'project' },
      { text: 'Likes short answers', kind: 'preference', layer: 'personal', supersedes: '20261124-120000-aaaa' },
    ])
    expect(parseReply('no json here')).toEqual([])
    expect(parseReply('{"memories": "nope"}')).toEqual([])
    expect(parseReply('{broken')).toEqual([])
  })

  test('plan skips duplicates and honours supersedes only for active ids it holds', () => {
    const old = mk('Deploy with Docker Compose')
    const kept = mk('Use pnpm, never npm', 'constraint')
    const p = plan(
      [
        { text: 'never use npm; use pnpm', kind: 'constraint', layer: 'project' },
        { text: 'Deploy with Kubernetes via Helm charts', kind: 'decision', layer: 'project', supersedes: old.id },
        { text: 'Ship releases on Tuesdays', kind: 'decision', layer: 'project', supersedes: '20200101-000000-zzzz' },
        { text: 'Ship releases on Tuesdays', kind: 'decision', layer: 'project' },
      ],
      [old, kept],
      { now: NOW, batch: 'cap-1', rand },
    )
    expect(p.add.map(m => m.text)).toEqual(['Deploy with Kubernetes via Helm charts', 'Ship releases on Tuesdays'])
    expect(p.add[1]?.supersedes).toBeUndefined()
    expect(p.supersede).toEqual([[old.id, p.add[0]!.id]])
    expect(p.skipped.map(s => s.why)).toEqual([`duplicate of ${kept.id}`, 'repeated in this batch'])
    expect(p.add.every(m => m.status === 'active' && m.batch === 'cap-1')).toBe(true)
  })
})

describe('book', () => {
  test('writes both layers to their folders and reads them back', async () => {
    const { io, files } = memIo()
    const b = new Book(io, dirsFor('/work/app', '/Users/me'))
    await b.apply({ add: [mk('Use pnpm', 'constraint'), mk('Prefers terse answers', 'preference', 'personal')], supersede: [] }, NOW)
    expect([...files.keys()].some(p => p.startsWith('/work/app/.claude/logbook/memory/'))).toBe(true)
    expect([...files.keys()].some(p => p.startsWith('/Users/me/.claude/logbook/memory/'))).toBe(true)
    const again = new Book(io, dirsFor('/work/app', '/Users/me'))
    await again.load()
    expect(again.all().map(m => m.layer).sort()).toEqual(['personal', 'project'])
    // The personal layer follows you to another folder; the project one does not.
    const elsewhere = new Book(io, dirsFor('/work/other', '/Users/me'))
    await elsewhere.load()
    expect(elsewhere.all().map(m => m.text)).toEqual(['Prefers terse answers'])
  })

  test('supersede, revoke and restore keep the chain', async () => {
    const { io } = memIo()
    const b = new Book(io, dirsFor('/w', '/h'))
    const old = mk('Deploy with Compose')
    await b.apply({ add: [old], supersede: [] }, NOW)
    const neu = { ...mk('Deploy with Helm charts'), supersedes: old.id }
    await b.apply({ add: [neu], supersede: [[old.id, neu.id]] }, NOW)
    expect(b.get(old.id)?.status).toBe('superseded')
    expect(b.get(old.id)?.supersededBy).toBe(neu.id)
    // Revoking the newer memory brings the one it replaced back.
    await b.setStatus(neu.id, 'revoked', NOW, 'wrong')
    expect(b.get(old.id)?.status).toBe('active')
    expect(await b.setStatus('20200101-000000-zzzz', 'revoked', NOW)).toContain('No memory')
    expect(await b.setStatus(old.id, 'active', NOW)).toContain('cannot move')
  })

  test('the home folder used as a project is personal only; broken files are listed, not fatal', async () => {
    expect(dirsFor('/Users/me', '/Users/me').project).toBeUndefined()
    const { io, files } = memIo()
    files.set('/w/.claude/logbook/memory/bad.md', 'not a memory')
    files.set(`/w/.claude/logbook/memory/${'x'}.txt`, 'ignored')
    const b = new Book(io, dirsFor('/w', undefined))
    await b.load()
    expect(b.all()).toEqual([])
    expect(b.broken).toEqual(['/w/.claude/logbook/memory/bad.md'])
  })

  test('undo finds the newest batch that still has active memories', async () => {
    const { io } = memIo()
    const b = new Book(io, dirsFor('/w', '/h'))
    await b.apply({ add: [{ ...mk('one', 'fact', 'project', new Date('2026-11-24T10:00:00Z')), batch: 'cap-a' }], supersede: [] }, NOW)
    await b.apply({ add: [{ ...mk('two', 'fact', 'project', new Date('2026-11-24T11:00:00Z')), batch: 'cap-b' }], supersede: [] }, NOW)
    expect(b.lastBatch()).toBe('cap-b')
  })
})
